#!/usr/bin/env node
/**
 * db:types — generate TypeScript types from the live database schema.
 *
 * Modes:
 *   node scripts/db-types.mjs          → write apps/prism-manage/src/types/database.types.ts
 *   node scripts/db-types.mjs --check  → generate to a temp file and fail if it
 *                                        differs from the committed types
 *                                        (schema-drift guard for CI)
 *
 * Connection resolution matches scripts/db-push.mjs:
 *   1. SUPABASE_DB_URL (full connection string)
 *   2. DATABASE_PASSWORD env var or apps/prism-manage/.env.local + pooler URL
 */
import { execSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_FILE = resolve(
  root,
  "apps/prism-manage/src/types/database.types.ts",
);
const checkMode = process.argv.includes("--check");

function parseEnvFile(path) {
  const out = {};
  if (!existsSync(path)) return out;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[trimmed.slice(0, eq).trim()] = value;
  }
  return out;
}

let dbUrl = process.env.SUPABASE_DB_URL || "";
if (!dbUrl) {
  const poolerUrlPath = resolve(root, "supabase/.temp/pooler-url");
  if (!existsSync(poolerUrlPath)) {
    if (checkMode) {
      // CI (or fresh checkouts) without a connection string: nothing to
      // compare against — skip rather than fail the pipeline.
      console.log(
        "db:types:check skipped — no SUPABASE_DB_URL and no linked project.",
      );
      process.exit(0);
    }
    console.error(
      "No connection string: set SUPABASE_DB_URL, or run `supabase link` once so supabase/.temp/pooler-url exists.",
    );
    process.exit(1);
  }
  const envLocal = parseEnvFile(resolve(root, "apps/prism-manage/.env.local"));
  const password = process.env.DATABASE_PASSWORD || envLocal.DATABASE_PASSWORD;
  if (!password) {
    console.error(
      "No database password: set SUPABASE_DB_URL or DATABASE_PASSWORD (env or apps/prism-manage/.env.local).",
    );
    process.exit(1);
  }
  const url = new URL(readFileSync(poolerUrlPath, "utf8").trim());
  url.password = password;
  dbUrl = url.toString();
}

// Resolve a working Supabase CLI (same strategy as db-push.mjs).
const candidates = [
  { probe: "pnpm exec supabase --version", run: "pnpm exec supabase" },
];
if (process.env.APPDATA) {
  const globalShim = `${process.env.APPDATA}\\npm\\supabase.cmd`;
  candidates.push({ probe: `"${globalShim}" --version`, run: `"${globalShim}"` });
}
candidates.push({ probe: "supabase --version", run: "supabase" });

const cli = candidates.find((c) => {
  try {
    execSync(c.probe, { stdio: "pipe", shell: true });
    return true;
  } catch {
    return false;
  }
});
if (!cli) {
  console.error("No working Supabase CLI found (npm i -g supabase).");
  process.exit(1);
}

const header =
  "// Generated by `pnpm db:types` — do not edit by hand.\n" +
  "// Regenerate after every migration; CI fails if this drifts from the live schema.\n";

let output;
try {
  output = execSync(`${cli.run} gen types typescript --db-url "${dbUrl}"`, {
    cwd: root,
    shell: true,
    maxBuffer: 64 * 1024 * 1024,
  }).toString();
} catch {
  console.error("db:types failed — see the Supabase CLI output above.");
  process.exit(1);
}

const next = header + output;

if (checkMode) {
  const current = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, "utf8") : "";
  if (current !== next) {
    console.error(
      "Schema drift detected: database.types.ts is out of date.\n" +
        "Run `pnpm db:types` and commit the result.",
    );
    process.exit(1);
  }
  console.log("Types are in sync with the live schema.");
} else {
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, next);
  console.log(`Wrote ${OUT_FILE}`);
}
